    var list = LocationDataHelper.allCities;

    if (selectedRegion != 'الكل') {
      list = list.where((c) => c.region == selectedRegion).toList();
    }

    final q = normalizeArabic(query);
    if (q.isEmpty) return list;

    final qTokens = q.split(' ').where((t) => t.isNotEmpty).toList();

    return list.where((city) {
      final normNameAr = normalizeArabic(city.nameAr);
      final normNameEn = normalizeArabic(city.nameEn);
      final normCountryAr = normalizeArabic(city.countryAr);
      final normCountryEn = normalizeArabic(city.countryEn);
      final normKeywords = city.searchKeywords.map(normalizeArabic).toList();

      final combined = '$normNameAr $normNameEn $normCountryAr $normCountryEn ${normKeywords.join(' ')}';

      return qTokens.every((token) => combined.contains(token));
    }).toList();
  }
