  /// Translates a city name to Arabic if an English name is provided
  static String toArabicCity(String cityName) {
    final trimmed = cityName.trim();
    if (trimmed.isEmpty) return trimmed;
    // If already contains Arabic characters, return as-is
    if (RegExp(r'[\u0600-\u06FF]').hasMatch(trimmed)) {
      return trimmed;
    }
    final lower = trimmed.toLowerCase();
    return _cityDictionary[lower] ?? trimmed;
  }

  /// Translates a country name/code to Arabic
  static String toArabicCountry(String countryName, [String countryCode = '']) {
    final trimmed = countryName.trim();
    if (trimmed.isNotEmpty && RegExp(r'[\u0600-\u06FF]').hasMatch(trimmed)) {
      return trimmed;
    }
    final lowerName = trimmed.toLowerCase();
    if (_countryDictionary.containsKey(lowerName)) {
      return _countryDictionary[lowerName]!;
    }
    final lowerCode = countryCode.trim().toLowerCase();
    if (_countryDictionary.containsKey(lowerCode)) {
      return _countryDictionary[lowerCode]!;
    }
    return trimmed.isNotEmpty ? trimmed : countryCode;
  }

  /// Converts any Location object into an Arabic-localized Location
  static Location toArabicLocation(Location loc) {
    return Location(
      id: loc.id,
      name: toArabicCity(loc.name),
      latitude: loc.latitude,
      longitude: loc.longitude,
      countryCode: loc.countryCode,
      countryName: toArabicCountry(loc.countryName, loc.countryCode),
      hasFixedPrayerTime: loc.hasFixedPrayerTime,
    );
  }

